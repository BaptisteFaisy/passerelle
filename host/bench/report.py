"""Comparative report and success thresholds (7.6, PERF-02, PERF-07).

Aggregates several runs -- this driver, client A, client B, the plain
`scp` copy and a reference Linux guest -- into one Markdown + JSON report,
checks the thresholds of section 7.6 for the requested level (socle,
complet, extreme) and renders the verdict PASS or FAIL per row.

Charts are optional: if matplotlib is importable a PNG is written,
otherwise a small SVG is generated by hand, so the tool never depends on
a third-party package to publish its numbers.
"""

from __future__ import annotations

import pathlib
from dataclasses import asdict, dataclass, field

from bench.loads import LoadResult
from bench.roundtrips import RoundtripTable, compare_tables
from pgwutil import dump_json, write_atomic
from pgwutil.svg import bar_chart

# Thresholds of section 7.6, per level.
LEVELS: dict[str, dict[str, float]] = {
    "socle": {"diff_ops": 100_000, "exercise_ops": 1_000_000, "workers": 1},
    "complet": {"diff_ops": 1_000_000, "exercise_ops": 10_000_000, "workers": 16},
    "extreme": {"diff_ops": 1_000_000, "exercise_ops": 10_000_000, "workers": 16},
}
MOUNT_LIMIT_MS = 50.0
PRIORITY_RATIO_LIMIT = 2.0
LINUX_SHARE = 0.5


@dataclass
class TargetRun:
    """Everything measured for one target (driver, A, B, scp, Linux)."""

    client: str
    label: str = ""
    workloads: dict[str, LoadResult] = field(default_factory=dict)
    roundtrips: RoundtripTable | None = None
    mount_time_ms: float = 0.0
    diff_ops: int = 0
    diff_divergences: int = 0
    exercise_ops: int = 0
    exercise_workers: int = 1
    exercise_mismatches: int = 0
    cases_passed: int = 0
    cases_total: int = 0
    leaks: int = 0
    fuzz_seconds: float = 0.0
    virtiofs: bool = False

    def throughput(self) -> float:
        """MiB/s of the throughput workload, or 0."""
        run = self.workloads.get("throughput")
        return run.throughput_mib_s if run else 0.0

    def metadata_rate(self) -> float:
        """Operations per second of the metadata workload, or 0."""
        run = self.workloads.get("metadata")
        return run.ops_per_second if run else 0.0

    def exec_rate(self) -> float:
        """Program launches per second, or 0."""
        run = self.workloads.get("exec")
        return run.ops_per_second if run else 0.0

    def priority_ratio(self) -> float:
        """Ratio of loaded to idle probe latency, or 0."""
        run = self.workloads.get("priority")
        return run.extra.get("ratio", 0.0) if run else 0.0

    def to_json(self) -> dict[str, object]:
        """JSON-serialisable form."""
        payload: dict[str, object] = {
            "client": self.client,
            "label": self.label,
            "mount_time_ms": self.mount_time_ms,
            "diff_ops": self.diff_ops,
            "diff_divergences": self.diff_divergences,
            "exercise_ops": self.exercise_ops,
            "exercise_workers": self.exercise_workers,
            "exercise_mismatches": self.exercise_mismatches,
            "cases_passed": self.cases_passed,
            "cases_total": self.cases_total,
            "leaks": self.leaks,
            "fuzz_seconds": self.fuzz_seconds,
            "virtiofs": self.virtiofs,
            "workloads": {name: asdict(run) for name, run in self.workloads.items()},
        }
        if self.roundtrips is not None:
            payload["roundtrips"] = self.roundtrips.to_json()
        return payload


@dataclass(frozen=True)
class Check:
    """One threshold verdict."""

    requirement: str
    measured: str
    threshold: str
    passed: bool


@dataclass
class Report:
    """The comparative report."""

    runs: list[TargetRun]
    level: str = "socle"
    checks: list[Check] = field(default_factory=list)

    @property
    def passed(self) -> bool:
        """True when every check passed."""
        return all(check.passed for check in self.checks)


def _find(runs: list[TargetRun], client: str) -> TargetRun | None:
    """Find a run by client name."""
    for run in runs:
        if run.client == client:
            return run
    return None


def evaluate(runs: list[TargetRun], level: str = "socle") -> list[Check]:
    """Check every threshold of section 7.6 for *level*."""
    limits = LEVELS.get(level, LEVELS["socle"])
    mine = _find(runs, "passerelle")
    if mine is None:
        return [Check("report includes this driver", "missing", "present", False)]
    checks = _conformance_checks(mine, limits)
    checks += _comparison_checks(runs, mine, level)
    checks += _level_checks(mine, level)
    return checks


def _conformance_checks(mine: TargetRun, limits: dict[str, float]) -> list[Check]:
    """Thresholds measured on this driver alone."""
    checks = [
        Check(
            "differential operations without divergence",
            f"{mine.diff_ops} ops / {mine.diff_divergences} divergences",
            f">= {int(limits['diff_ops'])} and 0 divergences",
            mine.diff_ops >= limits["diff_ops"] and mine.diff_divergences == 0,
        ),
        Check(
            "content exerciser operations",
            f"{mine.exercise_ops} ops / {mine.exercise_workers} workers",
            f">= {int(limits['exercise_ops'])} with {int(limits['workers'])} workers",
            mine.exercise_ops >= limits["exercise_ops"]
            and mine.exercise_workers >= limits["workers"],
        ),
        Check(
            "directed cases",
            f"{mine.cases_passed}/{mine.cases_total}",
            "all passed",
            mine.cases_total > 0 and mine.cases_passed == mine.cases_total,
        ),
        Check("leaks after one million opens", str(mine.leaks), "0", mine.leaks == 0),
        Check(
            "mount time (PERF-06)",
            f"{mine.mount_time_ms:.1f} ms" if mine.mount_time_ms > 0 else "not measured",
            f"< {MOUNT_LIMIT_MS:.0f} ms",
            0 < mine.mount_time_ms < MOUNT_LIMIT_MS,
        ),
    ]
    ratio = mine.priority_ratio()
    checks.append(
        Check(
            "priority read under bulk copy (PERF-05)",
            f"{ratio:.2f}x idle" if ratio else "not measured",
            f"<= {PRIORITY_RATIO_LIMIT:.1f}x",
            0 < ratio <= PRIORITY_RATIO_LIMIT,
        )
    )
    return checks


def _comparison_checks(runs: list[TargetRun], mine: TargetRun, level: str) -> list[Check]:
    """Thresholds that only mean something against another target."""
    checks: list[Check] = []
    linux = _find(runs, "linux")
    if linux is not None and linux.throughput() > 0:
        floor = linux.throughput() * LINUX_SHARE
        checks.append(
            Check(
                "throughput vs Linux guest (PERF-03)",
                f"{mine.throughput():.1f} MiB/s",
                f">= {floor:.1f} MiB/s (half of {linux.throughput():.1f})",
                mine.throughput() >= floor,
            )
        )
    for other in ("qnx-fs-9p", "eclipse"):
        rival = _find(runs, other)
        if rival is None:
            if level in ("complet", "extreme"):
                checks.append(Check(f"comparison against {other}", "missing", "present", False))
            continue
        checks.append(
            Check(
                f"throughput vs {other} (PERF-03)",
                f"{mine.throughput():.1f} vs {rival.throughput():.1f} MiB/s",
                "at least the best existing client",
                mine.throughput() >= rival.throughput(),
            )
        )
        if mine.roundtrips is not None and rival.roundtrips is not None:
            worse = compare_tables(mine.roundtrips, {other: rival.roundtrips})
            checks.append(
                Check(
                    f"roundtrips vs {other} (PERF-02)",
                    "no operation uses more roundtrips" if not worse else str(worse),
                    "never more than the best existing client",
                    not worse,
                )
            )
    return checks


def _level_checks(mine: TargetRun, level: str) -> list[Check]:
    """Thresholds that only apply at the complete or extreme level."""
    checks: list[Check] = []
    if level == "extreme":
        checks.append(
            Check(
                "virtiofs passes the same bench (VFS-05, VFS-07)",
                "present" if mine.virtiofs else "missing",
                "present",
                mine.virtiofs,
            )
        )
    if level in ("complet", "extreme"):
        checks.append(
            Check(
                "random inputs on the protocol parser",
                f"{mine.fuzz_seconds:.0f} s",
                ">= 3600 s without a fault",
                mine.fuzz_seconds >= 3600,
            )
        )
    return checks


def render_markdown(report: Report) -> str:
    """Render the comparative report as Markdown."""
    lines = [
        "# Passerelle comparative report (PERF-07)",
        "",
        f"Level: **{report.level}** -- verdict: **{'PASS' if report.passed else 'FAIL'}**",
        "",
        "| Target | Throughput (MiB/s) | Metadata (op/s) | Exec (op/s) | Priority ratio | Mount (ms) |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for run in report.runs:
        lines.append(
            f"| {run.label or run.client} | {run.throughput():.1f} | {run.metadata_rate():.0f} | "
            f"{run.exec_rate():.0f} | {run.priority_ratio():.2f}x | {run.mount_time_ms:.1f} |"
        )
    lines += ["", "## Thresholds (section 7.6)", "", "| Requirement | Measured | Threshold | Verdict |", "|---|---|---|---|"]
    for check in report.checks:
        lines.append(
            f"| {check.requirement} | {check.measured} | {check.threshold} | "
            f"{'PASS' if check.passed else 'FAIL'} |"
        )
    lines += ["", "## Roundtrips per POSIX operation", ""]
    for run in report.runs:
        if run.roundtrips is None:
            continue
        lines.append(f"### {run.label or run.client}")
        lines.append("")
        lines.append("| POSIX operation | requests | replies | roundtrips/call | mean ms |")
        lines.append("|---|---:|---:|---:|---:|")
        for row in run.roundtrips.rows:
            lines.append(
                f"| {row.operation} | {row.requests} | {row.replies} | "
                f"{row.roundtrips_per_call:.2f} | "
                f"{'n/a' if row.mean_latency_ms is None else f'{row.mean_latency_ms:.3f}'} |"
            )
        lines.append("")
    return "\n".join(lines)


def _svg_chart(report: Report) -> str:
    """Throughput bar chart, drawn by the single chart helper of the project."""
    return bar_chart(
        title="Throughput (MiB/s)",
        labels=[run.label or run.client for run in report.runs],
        values=[run.throughput() for run in report.runs],
    )


def _try_matplotlib_png(report: Report, path: pathlib.Path) -> bool:
    """Write a PNG with matplotlib when it happens to be installed."""
    try:
        import matplotlib  # type: ignore

        matplotlib.use("Agg")
        import matplotlib.pyplot as plt  # type: ignore
    except Exception:
        return False
    names = [run.label or run.client for run in report.runs]
    values = [run.throughput() for run in report.runs]
    figure, axes = plt.subplots(figsize=(7, 0.5 * len(names) + 1))
    axes.barh(names, values, color="#3b7dd8")
    axes.set_xlabel("MiB/s")
    figure.tight_layout()
    figure.savefig(path, dpi=120)
    plt.close(figure)
    return True


def write_report(report: Report, prefix: pathlib.Path | str) -> dict[str, pathlib.Path]:
    """Write the Markdown, JSON, SVG (and PNG when possible) report files."""
    base = pathlib.Path(prefix).expanduser().resolve()
    written: dict[str, pathlib.Path] = {}
    written["markdown"] = write_atomic(base.with_suffix(".md"), render_markdown(report))
    payload = {
        "level": report.level,
        "passed": report.passed,
        "checks": [asdict(check) for check in report.checks],
        "targets": [run.to_json() for run in report.runs],
    }
    written["json"] = write_atomic(base.with_suffix(".json"), dump_json(payload))
    written["svg"] = write_atomic(base.with_suffix(".svg"), _svg_chart(report))
    png = base.with_suffix(".png")
    if _try_matplotlib_png(report, png):
        written["png"] = png
    return written


def build_report(runs: list[TargetRun], level: str = "socle") -> Report:
    """Evaluate *runs* and return the report object."""
    return Report(runs=runs, level=level, checks=evaluate(runs, level))
