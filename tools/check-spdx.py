#!/usr/bin/env python3
# SPDX-License-Identifier: Apache-2.0
"""Check that every C/Python source file carries the Apache-2.0 SPDX header.

Project rule (see the hackathon brief): a source file starts with

    /* SPDX-License-Identifier: Apache-2.0 */

The Python flavour uses a `#` comment, usually on the line right after the
shebang. The marker is looked up in the first lines of the file, so a short
prologue (shebang, include guard) is accepted.

A file that declares *another* license is reported separately: the project
is Apache-2.0, so a foreign identifier usually means a file copied from a
third-party project (see NOTICE for the attributions).

Usage:
    python3 tools/check-spdx.py [--root .] [--quiet]

Exit status: 0 when every checked file is compliant, 1 otherwise.
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys

EXPECTED = "SPDX-License-Identifier: Apache-2.0"
SOURCE_EXTS = {".c", ".h", ".py"}
SKIP_DIRS = {".git", "__pycache__", ".venv", "venv", ".tox", "node_modules"}
# CMake build trees: generated, never tracked, regenerated by the CI.
BUILD_DIRS = ("build", "build-asan", "build-ci", "build-e2e")
# Vendored CI socle: maintained centrally, copied verbatim in every repo.
# Patches proposed to third-party projects keep their original license.
SKIP_PREFIXES = (".github/hermes/", ".github/ci-budget/", "upstream/")
HEADER_WINDOW = 8
LICENSE_RE = re.compile(r"SPDX-License-Identifier:\s*(\S+)")


def is_build_dir(name: str) -> bool:
    """True for a CMake build tree (never tracked, never checked)."""
    return name in BUILD_DIRS or name.startswith("build-")


def is_excluded(rel: pathlib.Path) -> bool:
    """True when the file must not be checked at all."""
    text = rel.as_posix()
    if any(text.startswith(prefix) for prefix in SKIP_PREFIXES):
        return True
    return any(part in SKIP_DIRS or is_build_dir(part) for part in rel.parts[:-1])


def header_block(path: pathlib.Path) -> str:
    """Return the first non-empty lines of the file (the header zone)."""
    lines: list[str] = []
    with path.open(encoding="utf-8", errors="replace") as handle:
        for line in handle:
            if line.strip():
                lines.append(line)
            if len(lines) >= HEADER_WINDOW:
                break
    return "".join(lines)


def check_file(rel: pathlib.Path, path: pathlib.Path) -> list[str]:
    """Return the violations of one file (empty list when compliant)."""
    block = header_block(path)
    if EXPECTED in block:
        return []
    found = LICENSE_RE.search(block)
    if found:
        return ["%s: license '%s', expected '%s'" % (rel, found.group(1), EXPECTED)]
    return ["%s: missing '%s' header" % (rel, EXPECTED)]


def check_tree(root: pathlib.Path) -> tuple[list[str], int]:
    """Return (violations, number of checked files) for the whole tree."""
    violations: list[str] = []
    checked = 0
    for path in sorted(root.rglob("*")):
        if not path.is_file() or path.suffix not in SOURCE_EXTS:
            continue
        rel = path.relative_to(root)
        if is_excluded(rel):
            continue
        checked += 1
        violations.extend(check_file(rel, path))
    return violations, checked


def main() -> int:
    parser = argparse.ArgumentParser(description="Check SPDX headers.")
    parser.add_argument("--root", default=".", help="tree to scan (default: .)")
    parser.add_argument("--quiet", action="store_true", help="only report problems")
    args = parser.parse_args()

    root = pathlib.Path(args.root).resolve()
    violations, checked = check_tree(root)
    for violation in violations:
        print("SPDX VIOLATION: %s" % violation, file=sys.stderr)
    if violations:
        print("spdx-guard: %d violation(s) in %d checked file(s)"
              % (len(violations), checked), file=sys.stderr)
        return 1
    if not args.quiet:
        print("spdx-guard: OK (%d file(s) checked)" % checked)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
