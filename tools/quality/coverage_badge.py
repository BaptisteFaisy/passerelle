"""Coverage badge: generate it, and check that the committed one is honest.

Gap 44 of docs/gap-analysis.md: the README showed no coverage badge, and the
badge one could have shown would have been decorative. This tool makes it
real, with two halves:

  * the *measurement* side: the `coverage` job of .github/workflows/
    quality.yml measures the coverage with gcov and writes
    build/coverage/summary.txt; this tool reads that summary, extracts the
    production-code percentage and writes the SVG badge plus a small JSON
    record (percentage, date, commit, tools);
  * the *check* side: `--check` recomputes the badge from the committed
    record and compares it with the committed SVG, so a badge that was
    edited by hand fails, and it refuses a record that is too old
    (`--max-age-days`), so a badge nobody refreshed fails too.

The SVG itself is drawn by covreport.badge_svg(), the function the coverage
report already uses: one drawing code, not two.

The committed files are:
    docs/_assets/coverage.svg    the badge shown by the README
    docs/_assets/coverage.json   the record: what was measured, and when

Usage:
    python3 tools/quality/coverage_badge.py --summary build/coverage/summary.txt
    python3 tools/quality/coverage_badge.py --check

Exit status: 0 ok, 1 the badge is inconsistent, stale or missing.
"""

from __future__ import annotations

import argparse
import datetime
import json
import pathlib
import re
import subprocess
import sys

if __package__ in (None, ""):  # allow `python3 tools/quality/coverage_badge.py`
    sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

import covreport

DEFAULT_SVG = pathlib.Path("docs") / "_assets" / "coverage.svg"
DEFAULT_RECORD = pathlib.Path("docs") / "_assets" / "coverage.json"
DEFAULT_MAX_AGE_DAYS = 30
DEFAULT_LABEL = "coverage"

#: The line of the coverage summary that carries the production score.
PRODUCTION_RE = re.compile(r"^PRODUCTION CODE\s*:\s*([0-9]+(?:\.[0-9]+)?)\s*%",
                           re.MULTILINE)
#: The tools that produced the measurement.
TOOLS_RE = re.compile(r"^tools:\s*(.+)$", re.MULTILINE)

SVG_HEADER = (
    "<!-- SPDX-License-Identifier: Apache-2.0 -->\n"
    "<!-- Generated by tools/quality/coverage_badge.py: do not edit by hand.\n"
    "     The source of truth is docs/_assets/coverage.json; the coverage job\n"
    "     of .github/workflows/quality.yml refreshes both on every push. -->\n"
)


def repo_root():
    """Return the root of the repository (the parent of tools/quality)."""
    return pathlib.Path(__file__).resolve().parents[2]


def parse_summary(path):
    """Return (percent, tools) of a coverage summary file."""
    text = pathlib.Path(path).read_text(encoding="utf-8")
    match = PRODUCTION_RE.search(text)
    if not match:
        raise ValueError("%s: no 'PRODUCTION CODE : x.xx %%' line" % path)
    tools = TOOLS_RE.search(text)
    return float(match.group(1)), (tools.group(1).strip() if tools else "unknown")


def render_svg(percent, label=DEFAULT_LABEL):
    """Return the badge SVG (with its header) for a percentage."""
    return SVG_HEADER + covreport.badge_svg(percent, label)


def read_record(path):
    """Read the measurement record and return it as a dictionary."""
    return json.loads(pathlib.Path(path).read_text(encoding="utf-8"))


def write_outputs(percent, record_path, svg_path, commit=None, tools="unknown",
                  label=DEFAULT_LABEL):
    """Write the badge and its record; return the SVG text."""
    now = datetime.datetime.now(datetime.timezone.utc).replace(microsecond=0)
    record = {
        "schema": "passerelle/coverage/1",
        "percent": round(float(percent), 2),
        "label": label,
        "measured_at": now.isoformat().replace("+00:00", "Z"),
        "commit": commit or "unknown",
        "tools": tools,
        "source": "quality.yml, job coverage (gcov, production C code)",
    }
    svg = render_svg(record["percent"], label)
    pathlib.Path(record_path).parent.mkdir(parents=True, exist_ok=True)
    pathlib.Path(record_path).write_text(
        json.dumps(record, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    pathlib.Path(svg_path).write_text(svg, encoding="utf-8")
    return svg


def git_commit(root):
    """Return the commit of the tree, or 'unknown'."""
    try:
        proc = subprocess.run(["git", "rev-parse", "HEAD"], cwd=root, text=True,
                              stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
                              timeout=30)
    except (OSError, subprocess.SubprocessError):
        return "unknown"
    return proc.stdout.strip() if proc.returncode == 0 else "unknown"


def check(record_path, svg_path, max_age_days):
    """Return the list of the problems of the committed badge."""
    problems = []
    record_path = pathlib.Path(record_path)
    svg_path = pathlib.Path(svg_path)
    if not record_path.is_file():
        return ["%s is missing: the coverage was never recorded" % record_path]
    if not svg_path.is_file():
        return ["%s is missing: the coverage badge was never written" % svg_path]
    try:
        record = read_record(record_path)
    except (OSError, ValueError) as err:
        return ["%s is not a readable JSON record: %s" % (record_path, err)]
    for field in ("percent", "measured_at", "commit"):
        if field not in record:
            problems.append("%s: field %r is missing" % (record_path, field))
    if problems:
        return problems
    expected = render_svg(float(record["percent"]),
                           record.get("label", DEFAULT_LABEL))
    actual = svg_path.read_text(encoding="utf-8")
    if actual != expected:
        problems.append("%s does not match the recorded percentage (%s%%): "
                        "the badge was edited by hand or the record is wrong"
                        % (svg_path, record["percent"]))
    age = age_in_days(record["measured_at"])
    if age is None:
        problems.append("%s: measured_at %r is not an ISO 8601 date"
                        % (record_path, record["measured_at"]))
    elif age > max_age_days:
        problems.append("the coverage badge is stale: it was measured %d days "
                        "ago (limit: %d). Refresh it with the coverage job."
                        % (age, max_age_days))
    return problems


def age_in_days(stamp):
    """Return the age of an ISO 8601 date in days, or None when unreadable."""
    try:
        when = datetime.datetime.fromisoformat(str(stamp).replace("Z", "+00:00"))
    except ValueError:
        return None
    now = datetime.datetime.now(datetime.timezone.utc)
    return (now - when).days


def needs_refresh(record_path, percent, label, refresh_days):
    """Tell whether the badge or its record must be rewritten.

    The badge is rewritten when the measured percentage moved, and the record
    is refreshed at least every `refresh_days` days, so that the age check
    of --check never fires on a tree nobody touched.
    """
    try:
        record = read_record(record_path)
    except (OSError, ValueError):
        return True
    try:
        same = round(float(record.get("percent", -1)), 2) == round(float(percent), 2)
    except (TypeError, ValueError):
        return True
    if not same:
        return True
    age = age_in_days(record.get("measured_at", ""))
    return age is None or age >= refresh_days


def parse_args(argv=None):
    """Parse the command line."""
    ap = argparse.ArgumentParser(description="Generate or check the coverage "
                                             "badge of the README.")
    ap.add_argument("--summary", default=None,
                    help="coverage summary written by run_coverage.py")
    ap.add_argument("--percent", type=float, default=None,
                    help="coverage percentage, when the summary is not at hand")
    ap.add_argument("--output", default=str(DEFAULT_SVG),
                    help="SVG badge to write (default: %s)" % DEFAULT_SVG)
    ap.add_argument("--record", default=str(DEFAULT_RECORD),
                    help="JSON record to write (default: %s)" % DEFAULT_RECORD)
    ap.add_argument("--check", action="store_true",
                    help="check the committed badge and its record")
    ap.add_argument("--max-age-days", type=int, default=DEFAULT_MAX_AGE_DAYS,
                    help="how old the record may be (default: %d)"
                         % DEFAULT_MAX_AGE_DAYS)
    ap.add_argument("--label", default=DEFAULT_LABEL, help="label of the badge")
    ap.add_argument("--commit", default=None,
                    help="commit to stamp in the record (default: HEAD)")
    ap.add_argument("--refresh-days", type=int, default=7,
                    help="refresh the record at least every N days (default: 7)")
    ap.add_argument("--force", action="store_true",
                    help="write the badge even when nothing changed")
    return ap.parse_args(argv)


def main(argv=None):
    """Generate the badge, or check the committed one."""
    args = parse_args(argv)
    root = repo_root()
    if args.check:
        problems = check(args.record, args.output, args.max_age_days)
        if problems:
            for problem in problems:
                print("coverage-badge: %s" % problem, file=sys.stderr)
            return 1
        print("coverage-badge: the committed badge matches its record")
        return 0
    if args.percent is None:
        if not args.summary:
            print("coverage-badge: --summary or --percent is required",
                  file=sys.stderr)
            return 1
        try:
            percent, tools = parse_summary(args.summary)
        except (OSError, ValueError) as err:
            print("coverage-badge: %s" % err, file=sys.stderr)
            return 1
    else:
        percent, tools = args.percent, "unknown"
    commit = args.commit or git_commit(root)
    if not args.force and not needs_refresh(args.record, percent, args.label,
                                             args.refresh_days):
        print("coverage-badge: %s is up to date (%.2f%%), nothing written"
              % (args.output, percent))
        return 0
    write_outputs(percent, args.record, args.output, commit, tools, args.label)
    print("coverage-badge: %s written (%.2f%%, commit %s)"
          % (args.output, percent, commit))
    return 0


if __name__ == "__main__":
    sys.exit(main())
